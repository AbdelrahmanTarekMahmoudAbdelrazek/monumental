import type { Silhouette } from "./types";

/**
 * Original silhouettes for the Mixed-mode categories (animals, nature, vehicles, space).
 * Same convention as silhouettes.ts: box `w` × 100, ground at y = 100, top of the
 * measured dimension at y = 0, clockwise sub-paths, nonzero fill.
 * Cut-outs (windows, craters, water streaks) are drawn counter-clockwise.
 */

type Pt = [number, number];
const poly = (pts: Pt[]) => "M" + pts.map((p) => p.map((n) => +n.toFixed(2)).join(",")).join(" L") + " Z";
/** counter-clockwise polygon → cut-out */
const hole = (pts: Pt[]) => poly([...pts].reverse());
const rect = (x: number, y: number, w: number, h: number) => poly([[x, y], [x + w, y], [x + w, y + h], [x, y + h]]);
const rectHole = (x: number, y: number, w: number, h: number) => hole([[x, y], [x + w, y], [x + w, y + h], [x, y + h]]);
const circle = (cx: number, cy: number, r: number) =>
  `M${cx - r},${cy} a${r},${r} 0 1 1 ${2 * r},0 a${r},${r} 0 1 1 ${-2 * r},0 Z`;
const circleHole = (cx: number, cy: number, r: number) =>
  `M${cx - r},${cy} a${r},${r} 0 1 0 ${2 * r},0 a${r},${r} 0 1 0 ${-2 * r},0 Z`;
const ellipse = (cx: number, cy: number, rx: number, ry: number) =>
  `M${cx - rx},${cy} a${rx},${ry} 0 1 1 ${2 * rx},0 a${rx},${ry} 0 1 1 ${-2 * rx},0 Z`;
const ellipseHole = (cx: number, cy: number, rx: number, ry: number) =>
  `M${cx - rx},${cy} a${rx},${ry} 0 1 0 ${2 * rx},0 a${rx},${ry} 0 1 0 ${-2 * rx},0 Z`;
/** ring = circle with a hole (wheels) */
const ring = (cx: number, cy: number, r: number, t: number) => circle(cx, cy, r) + " " + circleHole(cx, cy, r - t);
const join = (...p: string[]) => p.join(" ");
/** thin bar between two points (bicycle frames, ropes, booms) */
function bar(a: Pt, b: Pt, t: number) {
  const dx = b[0] - a[0], dy = b[1] - a[1];
  const len = Math.hypot(dx, dy) || 1;
  const nx = (-dy / len) * (t / 2), ny = (dx / len) * (t / 2);
  const pts: Pt[] = [[a[0] + nx, a[1] + ny], [b[0] + nx, b[1] + ny], [b[0] - nx, b[1] - ny], [a[0] - nx, a[1] - ny]];
  // make sure it is clockwise in screen space
  const area = pts.reduce((s, p, i) => { const q = pts[(i + 1) % 4]; return s + (p[0] * q[1] - q[0] * p[1]); }, 0);
  return poly(area > 0 ? pts : pts.reverse());
}
